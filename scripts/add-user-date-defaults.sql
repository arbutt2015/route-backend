-- Ensure DATE_CREATED / DATE_UPDATED are populated even when a USER row is
-- inserted outside the app (scripts, manual SQL) where TypeORM's
-- @CreateDateColumn/@UpdateDateColumn decorators don't run.

ALTER TABLE dbo.[USER]
ADD CONSTRAINT DF_USER_DATE_CREATED DEFAULT (SYSUTCDATETIME()) FOR DATE_CREATED;
GO

ALTER TABLE dbo.[USER]
ADD CONSTRAINT DF_USER_DATE_UPDATED DEFAULT (SYSUTCDATETIME()) FOR DATE_UPDATED;
GO

-- Same safety net for PROJECT and PROJECT_USER (same columns exist there).
ALTER TABLE dbo.PROJECT
ADD CONSTRAINT DF_PROJECT_DATE_CREATED DEFAULT (SYSUTCDATETIME()) FOR DATE_CREATED;
GO

ALTER TABLE dbo.PROJECT
ADD CONSTRAINT DF_PROJECT_DATE_UPDATED DEFAULT (SYSUTCDATETIME()) FOR DATE_UPDATED;
GO
